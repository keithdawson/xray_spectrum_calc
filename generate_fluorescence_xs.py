"""
Regenerates the per-element cross-section files in pyne_edpl/ from xraylib
(Scofield K-shell photoionization + incoherent scattering with binding
effects) on a fine energy grid.

Replaces the original EPDL-extracted files, which covered only 12 elements
on a coarse 1 keV grid that smeared the K-edge fluorescence onset. xraylib
and EPDL both derive from Scofield's calculations; spot checks agree to
better than 1%. Coverage: Z=11-92 (K fluorescence below Z=11 is sub-keV
and irrelevant here).

Grid: 0.1 keV from 1 to 500 keV, plus a pair of points 0.1 eV either side
of the K-edge so linear interpolation reproduces a sharp onset.

Columns (consumed by apply_filter_and_fluorescence.process_single_layer):
  E_keV                    : photon energy
  tauK_over_rho_cm2_per_g  : K-shell photoionization mass cross-section
  MT504                    : incoherent (Compton) mass cross-section

Usage: pip install xraylib && python generate_fluorescence_xs.py
"""

import numpy as np
import pandas as pd
import xraylib

E_MIN, E_MAX, E_STEP = 1.0, 500.0, 0.1
EDGE_EPS = 1e-4  # keV; half-width of the edge step pair


def tau_k(z, e_kev):
    try:
        return xraylib.CS_Photo_Partial(z, xraylib.K_SHELL, float(e_kev))
    except ValueError:  # below the K-edge
        return 0.0


def main():
    comb = np.round(np.arange(E_MIN, E_MAX + E_STEP / 2, E_STEP), 4)

    for z in range(11, 93):
        edge = xraylib.EdgeEnergy(z, xraylib.K_SHELL)
        grid = comb
        if E_MIN < edge < E_MAX:
            grid = np.union1d(comb, [edge - EDGE_EPS, edge + EDGE_EPS])

        tau = np.array([tau_k(z, e) for e in grid])
        incoh = np.array([xraylib.CS_Compt(z, float(e)) for e in grid])

        df = pd.DataFrame({
            'E_keV': grid,
            'tauK_over_rho_cm2_per_g': tau,
            'MT504': incoh,
        })
        out = f'pyne_edpl/ZA{z:03d}_extracted.csv'
        df.to_csv(out, index=False, float_format='%.6g')

    with open('pyne_edpl/SOURCE.txt', 'w', encoding='utf-8') as f:
        f.write(
            'These ZA###_extracted.csv files are generated by\n'
            'generate_fluorescence_xs.py from xraylib (Scofield cross-sections),\n'
            'replacing the original coarse-grid EPDL extracts. Do not edit by hand.\n'
        )
    print(f'Wrote pyne_edpl/ZA011..ZA092 ({len(comb)}+ points each)')


if __name__ == '__main__':
    main()
