"""
Generates fluorescence_k_data.py: K-shell fluorescence parameters and
Hubbell/Waller-Hartree atomic incoherent scattering functions S(q, Z) for
all elements, extracted from xraylib (Krause 1979 yields, rad-rate-weighted
line energies, K-beta/K-alpha branching, and SF_Compt).

Run this only to regenerate the data module; the app itself does not
require xraylib at runtime.

Usage: python generate_fluorescence_data.py
"""

import numpy as np
import xraylib
from pathlib import Path

SF_Q_MIN = 0.005
SF_Q_MAX = 50.0
SF_Q_POINTS = 80


def main():
    q_grid = np.geomspace(SF_Q_MIN, SF_Q_MAX, SF_Q_POINTS)
    lines = [
        '"""',
        'K-shell fluorescence and atomic incoherent scattering parameters,',
        'auto-generated by generate_fluorescence_data.py from xraylib %s.' % xraylib.__version__,
        'Do not edit by hand.',
        '',
        "Per element Z in FLUOR_K: 'yield' = Krause (1979) K fluorescence yield,",
        "'Ka'/'Kb' = radiative-rate-weighted mean K-alpha/K-beta energies (keV),",
        "'Kb_ratio' = K-beta/K-alpha radiative rate ratio,",
        "'K_edge' = K absorption edge energy (keV, for reference).",
        '',
        'INCOHERENT_SF_Q (1/Angstrom) and INCOHERENT_SF[Z] tabulate the',
        'Waller-Hartree / Hubbell et al. (1975) atomic incoherent scattering',
        'function S(q, Z) from xraylib.SF_Compt for Z=1..92.',
        '"""',
        '',
        'FLUOR_K = {',
    ]

    for z in range(11, 93):
        try:
            w_k = xraylib.FluorYield(z, xraylib.K_SHELL)
            e_ka = xraylib.LineEnergy(z, xraylib.KA_LINE)
            rate_ka = xraylib.RadRate(z, xraylib.KA_LINE)
            e_edge = xraylib.EdgeEnergy(z, xraylib.K_SHELL)
        except ValueError:
            continue
        # Na and Mg have no tabulated K-beta transition. They still have
        # valid K-alpha fluorescence and must not be dropped from the table.
        try:
            rate_kb = xraylib.RadRate(z, xraylib.KB_LINE)
        except ValueError:
            rate_kb = 0.0

        # Weighted K-beta energy from the principal components only; the
        # KB_LINE macro's energy is skewed by weak far-from-peak lines.
        kb_num = kb_den = 0.0
        for comp in ('KB1_LINE', 'KB2_LINE', 'KB3_LINE', 'KB4_LINE', 'KB5_LINE'):
            try:
                e = xraylib.LineEnergy(z, getattr(xraylib, comp))
                r = xraylib.RadRate(z, getattr(xraylib, comp))
                kb_num += e * r
                kb_den += r
            except ValueError:
                continue
        e_kb = kb_num / kb_den if kb_den > 0 else e_ka
        if w_k <= 0 or e_ka <= 0 or rate_ka <= 0:
            continue
        kb_ratio = rate_kb / rate_ka
        sym = xraylib.AtomicNumberToSymbol(z)
        lines.append(
            f"    {z}: {{'yield': {w_k:.4f}, 'Ka': {e_ka:.3f}, 'Kb': {e_kb:.3f}, "
            f"'Kb_ratio': {kb_ratio:.4f}, 'K_edge': {e_edge:.6f}}},  # {sym}"
        )

    lines.append('}')
    lines.append('')
    lines.append('# Standard atomic weights (g/mol), for electron-density calculations')
    lines.append('ATOMIC_MASS = {')
    for z in range(1, 93):
        a = xraylib.AtomicWeight(z)
        sym = xraylib.AtomicNumberToSymbol(z)
        lines.append(f'    {z}: {a:.4f},  # {sym}')
    lines.append('}')
    lines.append('')
    q_formatted = ', '.join(f'{float(q):.8g}' for q in q_grid)
    lines.append('# Momentum transfer q = (E_keV / 12.3984193) * sin(theta / 2) in 1/Angstrom')
    lines.append(f'INCOHERENT_SF_Q = ({q_formatted},)')
    lines.append('')
    lines.append('# Atomic incoherent scattering function S(q, Z) in [0, Z] (Hubbell et al. 1975)')
    lines.append('INCOHERENT_SF = {')
    for z in range(1, 93):
        sym = xraylib.AtomicNumberToSymbol(z)
        raw_sf = [float(f'{xraylib.SF_Compt(z, float(q)):.6g}') for q in q_grid]
        # Remove small cubic-spline overshoot and rounding jitter near S(q, Z) -> Z.
        monotonic_sf = np.minimum(np.maximum.accumulate(raw_sf), float(z))
        sf_vals = ', '.join(f'{float(v):.6g}' for v in monotonic_sf)
        lines.append(f'    {z}: ({sf_vals},),  # {sym}')
    lines.append('}')
    lines.append('')
    lines.append('# Atomic coherent (Rayleigh) form factor F(q, Z) in (0, Z] (Hubbell et al. 1975)')
    lines.append('COHERENT_FF = {')
    for z in range(1, 93):
        sym = xraylib.AtomicNumberToSymbol(z)
        raw_ff = [float(f'{xraylib.FF_Rayl(z, float(q)):.6g}') for q in q_grid]
        # Enforce monotonically nonincreasing F(q, Z) <= Z across the grid.
        monotonic_ff = np.maximum(np.minimum.accumulate(np.minimum(raw_ff, float(z))), 1e-30)
        ff_vals = ', '.join(f'{float(v):.6g}' for v in monotonic_ff)
        lines.append(f'    {z}: ({ff_vals},),  # {sym}')
    lines.append('}')
    lines.append('')

    with open(Path(__file__).resolve().with_name('fluorescence_k_data.py'), 'w', encoding='utf-8') as f:
        f.write('\n'.join(lines))
    print('Wrote fluorescence_k_data.py')


if __name__ == '__main__':
    main()
